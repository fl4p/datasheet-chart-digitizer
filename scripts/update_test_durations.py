#!/usr/bin/env python3
"""Regenerate tests/test_durations.txt from pytest --junitxml reports of COLD-cache full runs.

    scripts/update_test_durations.py junit.xml [junit2.xml ...] [--slow 2.0]

With several reports a test's time is its longest: in a cold run the RDS(VGS) tests share one
digitization per PDF, and which of them pays for it (or waits for it) changes from run to run.

Writes "<fast|slow> <seconds> <node id>" for every test of at least 0.3 s. conftest.py marks the
"slow" ones ``@pytest.mark.slow`` (deselected by the default ``-m "not slow"``) and starts the
longest tests first so that no long test is left for the end of an xdist run. A test file whose
tests would all be slow keeps its cheapest one fast, so the fast subset imports every test module.
Use a cold-cache run (fresh DSDIG_TEST_CACHE_DIR): warm OCR/render memos hide what a test costs
after a source change.
"""

from __future__ import annotations

import argparse
import collections
import xml.etree.ElementTree as ET
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "tests" / "test_durations.txt"
MIN_LISTED = 0.3


def node_id(case: ET.Element) -> str:
    parts = case.get("classname", "").split(".")
    for i in range(len(parts), 0, -1):    # tests.test_x.Class -> tests/test_x.py::Class
        if parts[i - 1].startswith("test_"):
            path = "/".join(parts[:i]) + ".py"
            return "::".join([path, *parts[i:], case.get("name", "")])
    raise ValueError(f"cannot map {case.attrib} to a node id")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("junit", nargs="+")
    ap.add_argument("--slow", type=float, default=2.0, help="seconds at or above which a test is slow")
    args = ap.parse_args()
    times: dict[str, float] = {}
    for report in args.junit:
        run: dict[str, float] = {}
        for case in ET.parse(report).iter("testcase"):
            if not case.get("classname"):     # a module-level skip/collection record, not a test
                continue
            nid = node_id(case)
            run[nid] = run.get(nid, 0.0) + float(case.get("time", 0))
        for nid, t in run.items():
            times[nid] = max(times.get(nid, 0.0), t)
    by_file = collections.defaultdict(list)
    for nid, t in times.items():
        by_file[nid.split("::", 1)[0]].append((t, nid))
    keep_fast = {min(rows)[1] for rows in by_file.values() if all(t >= args.slow for t, _ in rows)}
    lines = [f"# generated by scripts/update_test_durations.py from a cold-cache run; slow >= {args.slow} s",
             "# <fast|slow> <seconds> <node id>; tests under 0.3 s are not listed (fast)"]
    for nid, t in sorted(times.items(), key=lambda kv: (-kv[1], kv[0])):
        if t < MIN_LISTED and nid not in keep_fast:
            continue
        lines.append(f"{'slow' if t >= args.slow and nid not in keep_fast else 'fast'} {t:.2f} {nid}")
    OUT.write_text("\n".join(lines) + "\n")
    slow = sum(1 for line in lines if line.startswith("slow"))
    print(f"{OUT}: {len(times)} tests, {slow} slow, {len(keep_fast)} kept fast as their file's only test")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
